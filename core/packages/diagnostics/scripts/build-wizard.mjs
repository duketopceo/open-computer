// Bundles the web wizard into one HTML string module for the cloud core (no static asset hosting needed).
// `node scripts/build-wizard.mjs` writes it; `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { build } from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.join(here, "..");
const out = path.join(pkg, "..", "cloud", "src", "wizard", "page.ts");

const handler = readFileSync(path.join(pkg, "..", "cloud", "src", "handler.ts"), "utf8");
const version = /export const VERSION = "([^"]+)"/.exec(handler)?.[1];
if (!version) throw new Error("VERSION not found in handler.ts");

const result = await build({
  entryPoints: [path.join(pkg, "src", "browser.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2022",
  write: false,
  legalComments: "none",
  define: { __APP_VERSION__: JSON.stringify(version) },
});
const js = (result.outputFiles[0]?.text ?? "").replace(/<\/script/gi, "<\\/script");
const css = readFileSync(path.join(pkg, "src", "page.css"), "utf8");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="dark light">
<title>Open Computer setup and tests</title>
<style>${css}</style>
</head>
<body>
<main>
<h1>Open Computer: setup and tests</h1>
<p class="lede">Checks your backend step by step, with timing. Nothing is sent anywhere except to your own core.</p>
<section class="panel" aria-label="Connection">
<label for="backend">Backend</label>
<select id="backend">
<option value="cloudflare" selected>Cloudflare (this core)</option>
<option value="self-hosted">Self-hosted server</option>
<option value="local">This computer only</option>
</select>
<div id="url-row" hidden><label for="url">Core address</label><input id="url" type="url" placeholder="https://core.example.com" autocomplete="off"></div>
<label for="token">Access token</label>
<input id="token" type="password" autocomplete="off" spellcheck="false">
<div class="actions"><button id="run" type="button">Run tests</button><button id="export" class="secondary" type="button" hidden>Export results JSON</button><span id="status" role="status"></span></div>
</section>
<nav class="tabs" aria-label="Sections"><button id="tab-tests" class="tab on" type="button">Tests</button><button id="tab-chat" class="tab" type="button">Chat</button><button id="tab-settings" class="tab" type="button">Settings</button></nav>
<div id="view-tests"><ol id="rows" aria-live="polite"></ol>
<section id="summary" hidden></section></div>
<div id="view-chat" hidden>
<ol id="chat-items" aria-live="polite"></ol>
<p id="chat-working" class="detail" hidden></p>
<div class="composer"><input id="goal" type="text" placeholder="What should Open Computer do?" autocomplete="off"><button id="send" type="button">Send</button><button id="stop" class="secondary" type="button" hidden>Stop</button></div>
<p id="chat-footer" class="detail"></p>
</div>
<div id="view-settings" hidden><section class="panel" id="settings-body"></section></div>
</main>
<script>${js}</script>
</body>
</html>
`;

const file = `// GENERATED by core/packages/diagnostics/scripts/build-wizard.mjs. Do not edit; run \`pnpm --filter @open-computer/diagnostics build:wizard\`.
export const WIZARD_HTML = ${JSON.stringify(html)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (current !== file) {
    console.error("cloud/src/wizard/page.ts is stale. Run: pnpm --filter @open-computer/diagnostics build:wizard");
    process.exit(1);
  }
  console.log("wizard page is up to date");
} else {
  writeFileSync(out, file);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${file.length} bytes)`);
}
